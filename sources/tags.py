def make_tag(category, symbol):
    sym = re.sub(r"[\s:]+", "_", str(symbol).strip().lower())
    return f"{category}:{sym}"


def currency_symbol(name):
    """-> (نماد، تعداد واحد) یا None اگر نام در نگاشت نباشد"""
    return CURRENCIES.get(norm(name))


def gold_symbol(name):
    return GOLD.get(norm(name))
